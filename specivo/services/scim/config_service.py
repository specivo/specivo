"""A provider's SCIM switch and bearer token, and authentication of SCIM requests.

The token is generated by an administrator, shown once, and stored as its
SHA-256 hash (as API keys are); its first characters are kept so the admin can
tell an old token from a new one. Rotating replaces the hash, so the old token
stops working at once. Revoking removes it and switches SCIM off, because SCIM
can be on only while a token exists (``ck_sso_providers_scim_needs_token``).

:meth:`ScimConfigService.authenticate` answers ``None`` alike for an unknown
slug, a disabled provider, a provider with SCIM off or without a token, and a
wrong token, after
the same hash and constant-time comparison, so neither the answer nor its
timing says which.
"""

from __future__ import annotations

import hashlib
import hmac
import secrets
from datetime import timedelta

from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession

from specivo.core.config import Settings, get_settings
from specivo.core.exceptions import AppError
from specivo.core.i18n import gettext as _
from specivo.core.utils import utcnow
from specivo.models.scim import ScimResource
from specivo.models.sso import SsoProvider
from specivo.models.user import User
from specivo.schemas.sso import ScimSettingsOut
from specivo.services.scim import events

__all__ = ["SCIM_TOKEN_PREFIX", "ScimConfigService", "hash_scim_token", "scim_base_url"]

#: Every SCIM token starts with this, so a leaked one is recognisable (and is never taken for an API key).
SCIM_TOKEN_PREFIX = "spvscim_"
_TOKEN_ENTROPY_BYTES = 32
_SHOWN_PREFIX_LENGTH = 14
# ``scim_last_used_at`` is written at most this often.
_LAST_USED_DEBOUNCE = timedelta(seconds=60)
# Compared against when the provider has no token, so that path costs the same.
_DUMMY_HASH = hashlib.sha256(b"no scim token").hexdigest()


def hash_scim_token(raw: str) -> str:
    """SHA-256 hex digest of a raw SCIM token."""
    return hashlib.sha256(raw.encode()).hexdigest()


def scim_base_url(slug: str, settings: Settings | None = None) -> str:
    """The SCIM base URL to paste into the IdP: ``APP_URL`` + stealth prefix + ``/scim/v2/{slug}``.

    Without a trailing slash: clients append ``/Users`` and ``/Groups``.
    """
    settings = settings or get_settings()
    return f"{settings.app_url.rstrip('/')}{settings.stealth_prefix.rstrip('/')}/scim/v2/{slug}"


class ScimConfigService:
    """Stateless; the state lives on the ``SsoProvider`` row."""

    async def generate_token(self, db: AsyncSession, provider: SsoProvider, *, actor: User | None) -> str:
        """Create (or rotate to) a new token and return it; this is the only time it is visible."""
        rotated = provider.scim_token_hash is not None
        raw = SCIM_TOKEN_PREFIX + secrets.token_urlsafe(_TOKEN_ENTROPY_BYTES)
        provider.scim_token_hash = hash_scim_token(raw)
        provider.scim_token_prefix = raw[:_SHOWN_PREFIX_LENGTH]
        provider.scim_token_created_at = utcnow()
        await db.flush()
        events.config_changed(
            provider_id=provider.id,
            provider_slug=provider.slug,
            actor_id=actor.id if actor else None,
            action="token_rotated" if rotated else "token_generated",
        )
        return raw

    async def revoke_token(self, db: AsyncSession, provider: SsoProvider, *, actor: User | None) -> None:
        """Remove the token and switch SCIM off."""
        provider.scim_enabled = False
        provider.scim_token_hash = None
        provider.scim_token_prefix = None
        provider.scim_token_created_at = None
        await db.flush()
        events.config_changed(
            provider_id=provider.id,
            provider_slug=provider.slug,
            actor_id=actor.id if actor else None,
            action="token_revoked",
        )

    async def set_enabled(self, db: AsyncSession, provider: SsoProvider, enabled: bool, *, actor: User | None) -> None:
        """Switch SCIM on or off; on needs a token (400 ``scim_token_required``)."""
        if enabled == provider.scim_enabled:
            return
        if enabled and provider.scim_token_hash is None:
            raise AppError(
                code="scim_token_required",
                message=_("Generate a SCIM token before turning provisioning on."),
                status_code=400,
                field="enabled",
            )
        provider.scim_enabled = enabled
        await db.flush()
        events.config_changed(
            provider_id=provider.id,
            provider_slug=provider.slug,
            actor_id=actor.id if actor else None,
            action="enabled" if enabled else "disabled",
        )

    async def authenticate(self, db: AsyncSession, slug: str, authorization: str | None) -> SsoProvider | None:
        """The provider whose SCIM token ``authorization`` (``Bearer <token>``) carries, or ``None``."""
        presented = ""
        if authorization:
            scheme, _sep, credentials = authorization.partition(" ")
            if scheme.lower() == "bearer":
                presented = credentials.strip()
        provider = (await db.execute(select(SsoProvider).where(SsoProvider.slug == slug))).scalar_one_or_none()
        expected = provider.scim_token_hash if provider is not None and provider.scim_token_hash else _DUMMY_HASH
        matches = hmac.compare_digest(hash_scim_token(presented), expected)
        if (
            provider is None
            or not provider.enabled
            or not provider.scim_enabled
            or provider.scim_token_hash is None
            or not presented
        ):
            return None
        return provider if matches else None

    async def touch(self, db: AsyncSession, provider: SsoProvider) -> None:
        """Record the time of an authenticated request (debounced)."""
        now = utcnow()
        if provider.scim_last_used_at is None or now - provider.scim_last_used_at >= _LAST_USED_DEBOUNCE:
            provider.scim_last_used_at = now
            await db.flush()

    async def resource_counts(self, db: AsyncSession, provider_id: int) -> dict[str, int]:
        """How many live users and groups the provider's SCIM manages."""
        rows = await db.execute(
            select(ScimResource.resource_type, func.count())
            .where(ScimResource.provider_id == provider_id, ScimResource.deleted_at.is_(None))
            .group_by(ScimResource.resource_type)
        )
        counts = {kind: int(n) for kind, n in rows.all()}
        return {"users": counts.get("User", 0), "groups": counts.get("Group", 0)}

    async def settings_out(self, db: AsyncSession, provider: SsoProvider) -> ScimSettingsOut:
        """The provider's SCIM settings as the admin API shows them (never the token)."""
        counts = await self.resource_counts(db, provider.id)
        return ScimSettingsOut(
            enabled=provider.scim_enabled,
            base_url=scim_base_url(provider.slug),
            token_configured=provider.scim_token_hash is not None,
            token_prefix=provider.scim_token_prefix,
            token_created_at=provider.scim_token_created_at,
            last_request_at=provider.scim_last_used_at,
            user_count=counts["users"],
            group_count=counts["groups"],
            claim_group_sync_skipped=provider.scim_enabled and provider.sync_groups,
        )
